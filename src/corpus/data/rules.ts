// PagaMenos · Corpus v1 — the 46 active rule instances + operational states + excluded history.
// Faithful encoding of the hardened Phase 0A-1B rule tables. Where a source states only an end
// date (start unknown), the rule is encoded as OBSERVED_ACTIVE_UNTIL: `observedActiveAt` is the
// freeze observation date (2026-08-30) as PROVENANCE — it is NOT stored as a provider-declared
// campaign start, and no earlier start date is invented. Money = integer céntimos; nominal
// value = integer minor units.
import { FREEZE_TIMESTAMP, OBSERVED_AT } from '../ids';
import type {
  AvailabilityState,
  Channel,
  EligibilityClass,
  EligibleSpendSelector,
  HolidayPolicy,
  MerchantId,
  ProviderFamily,
  PurchaseSignatureKind,
  Weekday,
} from '../ids';
import type {
  Benefit,
  CanonicalItemQty,
  Cap,
  ExcludedRule,
  NonCashNominalBenefit,
  RuleOperationalState,
  RuleVersion,
  TemporalRange,
} from '../types';
import { SOURCES } from './merchants';

const SOURCE_URL = new Map(SOURCES.map((s) => [s.sourceId, s.url]));

const dr = (start: string, end: string): TemporalRange => ({
  kind: 'LOCAL_DATE_RANGE',
  startDateInclusive: start,
  endDateInclusive: end,
});
// Source gives only an end date: observed active at `observedActiveAt` (provenance, NOT a
// provider-declared start) through the published `end`. No earlier start is invented.
const oau = (observedActiveAt: string, end: string): TemporalRange => ({
  kind: 'OBSERVED_ACTIVE_UNTIL',
  observedActiveAt,
  endDateInclusive: end,
});
const cap = (centimos: number): Cap => ({ kind: 'AMOUNT', centimos });
const CAP_UNKNOWN: Cap = { kind: 'UNKNOWN_NOT_STATED' };

const pct = (bps: number): Benefit => ({
  type: 'PERCENT',
  percentBps: bps,
  rounding: 'FLOOR_TO_CENT',
});
const fprice = (price: number, regular?: number): Benefit => ({
  type: 'FIXED_PRICE',
  fixedPriceCentimos: price,
  ...(regular !== undefined ? { regularReferenceCentimos: regular } : {}),
});
const fbundle = (price: number, regular: number): Benefit => ({
  type: 'FIXED_BUNDLE',
  bundlePriceCentimos: price,
  regularReferenceCentimos: regular,
});
const twoForOne = (pay: number, of: number): Benefit => ({ type: 'TWO_FOR_ONE', pay, of });
const nominal = (minorUnits: number, cash: number): NonCashNominalBenefit => ({
  type: 'NON_CASH_NOMINAL',
  nominalMinorUnits: minorUnits,
  nominalUnit: 'CONEY_PLAY_BALANCE',
  cashAcquisitionCostCentimos: cash,
});

interface RuleInput {
  id: string;
  family: ProviderFamily;
  merchant: MerchantId;
  merchants?: MerchantId[];
  benefit: Benefit;
  selector: EligibleSpendSelector;
  sig: PurchaseSignatureKind;
  scopes: string[];
  temporal: TemporalRange;
  holiday: HolidayPolicy;
  channels: Channel[];
  cap?: Cap;
  weekdays?: Weekday[];
  locations?: { include?: string[]; exclude?: string[] };
  stock?: boolean;
  eligibility: EligibilityClass;
  source: string;
  items?: CanonicalItemQty[];
  ticket?: { ticketCount: number; ticketClass: string };
  privateKey?: string;
  cardNetwork?: 'AMEX' | 'VISA' | 'MC' | 'ANY';
  membership?: string;
  confidence?: 'HIGH' | 'MEDIUM' | 'LOW';
}

interface Built {
  rule: RuleVersion;
  op: RuleOperationalState;
}

function mk(i: RuleInput): Built {
  const availability: AvailabilityState = i.stock ? 'UNKNOWN' : 'NOT_APPLICABLE';
  const rule: RuleVersion = {
    ruleId: i.id,
    version: 1,
    campaignId: `cmp_${i.id}`,
    merchantIds: i.merchants ?? [i.merchant],
    providerFamily: i.family,
    benefit: i.benefit,
    eligibleSpendSelector: i.selector,
    ...(i.items ? { canonicalItems: i.items } : {}),
    ...(i.ticket ? { ticketContext: i.ticket } : {}),
    constraints: {
      temporal: i.temporal,
      holidayPolicy: i.holiday,
      channels: i.channels,
      combinability: 'NO',
      ...(i.cap ? { cap: i.cap } : {}),
      ...(i.weekdays ? { weekdays: i.weekdays } : {}),
      ...(i.locations ? { locations: i.locations } : {}),
      ...(i.stock ? { stock: { known: false } } : {}),
      ...(i.cardNetwork ? { cardNetwork: i.cardNetwork } : {}),
      ...(i.membership ? { membership: i.membership } : {}),
      ...(i.privateKey ? { providerPrivateKey: i.privateKey } : {}),
    },
    eligibilityClass: i.eligibility,
    confidence: i.confidence ?? 'HIGH',
    comparisonScopeRefs: i.scopes,
    signatureKind: i.sig,
    provenance: {
      sourceId: i.source,
      url: SOURCE_URL.get(i.source) ?? '',
      observedAt: OBSERVED_AT,
    },
  };
  const op: RuleOperationalState = {
    ruleId: i.id,
    version: 1,
    publicationState: 'ACTIVE',
    sourceQualityState: 'FRESH',
    availability,
    asOf: FREEZE_TIMESTAMP,
  };
  return { rule, op };
}

